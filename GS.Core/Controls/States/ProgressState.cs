namespace GS.Core.UI.Controls
{
    /// <summary>
    /// Estados visuais de componentes que exibem progresso.
    /// </summary>
    public enum ProgressState
    {
        /// <summary>
        /// Estado padrão.
        /// </summary>
        Normal,

        /// <summary>
        /// Progresso concluído com sucesso.
        /// </summary>
        Success,

        /// <summary>
        /// Progresso concluído com erro.
        /// </summary>
        Error
    }
}
